@unittest.skipUnless(os.getenv('BACKUP_TEST_POSTGRES') == '1', 'Opt-in PostgreSQL/age integration fixture')
class PostgresTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.pg = dict(os.environ, PGHOST='127.0.0.1', PGPORT='55439',
                       PGUSER=getpass.getuser(), PGDATABASE='postgres', PGSSLMODE='disable')
        self.source = 'backup_source_' + uuid.uuid4().hex[:10]
        self.target = 'backup_target_' + uuid.uuid4().hex[:10]
        for name in ['postgres', 'anon', 'authenticated']:
            if self.sql(f"SELECT count(*) FROM pg_roles WHERE rolname='{name}'").strip() == '0':
                self.sql(f'CREATE ROLE {name}' + (' SUPERUSER' if name == 'postgres' else ''))
        for name in [self.source, self.target]:
            self.sql(f'CREATE DATABASE {name}')
            self.addCleanup(self.sql, f'DROP DATABASE IF EXISTS {name} WITH (FORCE)')
        self.sql(MANAGED + APP, self.source)
        self.sql(MANAGED, self.target)
        self.runner = load('runner')
        self.backup = self.runner.Backup(dict(os.environ) | ENV)
        self.backup.settings['db_env'] = {key: value for key, value in self.pg.items() if key.startswith('PG')}
        self.backup.settings['db_env']['PGDATABASE'] = self.source

    def sql(self, sql, database='postgres'):
        return subprocess.run(['psql', '-XAt', '-v', 'ON_ERROR_STOP=1'], input=sql,
                              env=self.pg | {'PGDATABASE': database}, check=True,
                              capture_output=True, text=True).stdout

    def test_real_export_restores_auth_hashes_relationships_rls_and_sequences(self):
        content = self.root / 'content'
        content.mkdir()
        self.backup.export(content)
        (content / 'organization.json').write_text('{"name":"Example Community"}')
        load('archive').build(content, self.root / 'backup.tar.gz', {'commit': 'synthetic'})
        self.assertIn('fixture_auth_profile', (content / 'managed-schema.sql').read_text())
        for name in ['schema.sql', 'data.sql']:
            sql = (content / name).read_text()
            if name == 'data.sql':
                # Even if an app trigger already exists on the target, restoration
                # must not create duplicate profiles while replaying auth.users.
                self.sql('CREATE TRIGGER fixture_auth_profile AFTER INSERT ON auth.users '
                         'FOR EACH ROW EXECUTE FUNCTION public.fixture_profile()', self.target)
                sql = 'SET session_replication_role=replica;\n' + sql
            self.sql(sql, self.target)
        self.assertEqual(self.sql("SELECT crypt('fixture-only', encrypted_password)=encrypted_password FROM auth.users", self.target).strip(), 't')
        self.assertEqual(self.sql('SELECT count(*) FROM auth.identities i JOIN public.users u ON u.id=i.user_id JOIN public.items t ON t.user_id=u.id', self.target).strip(), '1')
        self.assertEqual(self.sql("INSERT INTO public.items(user_id) VALUES('00000000-0000-0000-0000-000000000001') RETURNING id", self.target).splitlines()[0], '2')
        self.assertIn('0', self.sql('SET ROLE authenticated; SELECT count(*) FROM public.items', self.target).splitlines())
        self.assertIn('2', self.sql("SET fixture.user_id='00000000-0000-0000-0000-000000000001'; SET ROLE authenticated; SELECT count(*) FROM public.items", self.target).splitlines())
        self.sql("INSERT INTO auth.users(id) VALUES('00000000-0000-0000-0000-000000000003')", self.target)
        self.assertEqual(self.sql('SELECT count(*) FROM public.users', self.target).strip(), '2')
        self.assertEqual(self.sql('SELECT id FROM private.recovery_fixture', self.target).strip(), '42')

    def test_template_registration_triggers_and_policy_survive_recovery(self):
        # Exercise the actual template migration against synthetic managed tables.
        for database in [self.source, self.target]:
            self.sql('ALTER TABLE auth.users ADD email_change text, ADD raw_user_meta_data jsonb, ADD email_confirmed_at timestamptz', database)
        self.sql('''
            DROP TRIGGER fixture_auth_profile ON auth.users;
            ALTER TABLE public.users ADD email text, ADD display_name text, ADD campus_id uuid,
              ADD email_verified boolean, ADD email_verified_at timestamptz;
            CREATE TABLE public.notifications(user_id uuid, type text, title text, message text, action_url text);
        ''', self.source)
        migration = Path(__file__).resolve().parents[3] / 'supabase/migrations/20260924072811_enforce_organization_policy.sql'
        self.sql(migration.read_text(), self.source)
        triggers = self.sql("""SELECT pg_get_triggerdef(oid) || ';' FROM pg_trigger
            WHERE tgrelid='auth.users'::regclass AND NOT tgisinternal ORDER BY tgname""", self.source)
        content = self.root / 'content'
        content.mkdir()
        self.backup.export(content)
        self.sql((content / 'schema.sql').read_text() + '\nSET session_replication_role=replica;\n'
                 + (content / 'data.sql').read_text() + '\nSET session_replication_role=origin;\n' + triggers, self.target)
        self.sql("INSERT INTO auth.users(id,email) VALUES('00000000-0000-0000-0000-000000000003','member@example.org')", self.target)
        self.assertEqual(self.sql("SELECT campus_id FROM public.users WHERE email='member@example.org'", self.target).strip(),
                         '00000000-0000-0000-0000-000000000010')
        self.assertEqual(self.sql("SELECT count(*) FROM public.notifications WHERE user_id='00000000-0000-0000-0000-000000000003'", self.target).strip(), '1')
        with self.assertRaises(subprocess.CalledProcessError):
            self.sql("INSERT INTO auth.users(id,email) VALUES('00000000-0000-0000-0000-000000000004','member@other.example')", self.target)
        with self.assertRaises(subprocess.CalledProcessError):
            self.sql("UPDATE auth.users SET email_change='member@other.example' WHERE email='member@example.org'", self.target)
        self.sql("UPDATE auth.users SET email_confirmed_at=now() WHERE email='member@example.org'", self.target)
        self.assertEqual(self.sql("SELECT email_verified FROM public.users WHERE email='member@example.org'", self.target).strip(), 't')

    def test_private_function_change_during_export_aborts_backup(self):
        self.sql('CREATE FUNCTION private.fixture() RETURNS int LANGUAGE sql AS $$SELECT 1$$', self.source)
        content = self.root / 'content'
        content.mkdir()
        command = self.backup.command
        def concurrent_migration(args, *positional, **kwargs):
            result = command(args, *positional, **kwargs)
            if args[0] == 'pg_dump' and '--data-only' in args:
                self.sql('CREATE OR REPLACE FUNCTION private.fixture() RETURNS int LANGUAGE sql AS $$SELECT 2$$', self.source)
            return result
        with patch.object(self.backup, 'command', side_effect=concurrent_migration):
            with self.assertRaisesRegex(self.runner.BackupError, 'Schema changed'):
                self.backup.export(content)

    def test_non_bypass_role_is_refused_before_export(self):
        content = self.root / 'content'
        content.mkdir()
        self.backup.settings['db_env']['PGOPTIONS'] = '-c role=authenticated'
        with self.assertRaisesRegex(self.runner.BackupError, 'RLS-bypassing'):
            self.backup.export(content)
        self.assertFalse((content / 'data.sql').exists())

    def test_rls_change_during_export_aborts_backup(self):
        content = self.root / 'content'
        content.mkdir()
        command = self.backup.command
        def concurrent_migration(args, *positional, **kwargs):
            result = command(args, *positional, **kwargs)
            if args[0] == 'pg_dump' and '--data-only' in args:
                self.sql('ALTER TABLE public.empty ENABLE ROW LEVEL SECURITY', self.source)
            return result
        with patch.object(self.backup, 'command', side_effect=concurrent_migration):
            with self.assertRaises(self.runner.BackupError):
                self.backup.export(content)

    def test_full_pipeline_encrypts_verifies_upload_and_prunes_only_old_pairs(self):
        identity = self.root / 'identity'
        subprocess.run(['age-keygen', '-o', str(identity)], check=True, capture_output=True)
        recipient = subprocess.run(['age-keygen', '-y', str(identity)], check=True, capture_output=True, text=True).stdout.strip()
        self.backup.settings['recipient'] = recipient
        self.backup.temp_root = self.root
        remote = {}
        for day in range(1, 9):
            key = f'lostopedia/database/202609{day:02d}T000000Z-{day}-1.tar.age'
            remote[key] = b'old'
            remote[key + '.complete.json'] = json.dumps({'key': key, 'size': 3, 'sha256': 'a' * 64, 'completed_at': '2026-09-01T00:00:00+00:00'}).encode()
        remote['unrelated/keep'] = b'untouched'
        def s3(args, output=None):
            if args[:2] == ['s3', 'cp']:
                source, destination = args[2:4]
                if source.startswith('s3://'):
                    Path(destination).write_bytes(remote[source.split('/', 3)[3]])
                else:
                    remote[destination.split('/', 3)[3]] = Path(source).read_bytes()
                return ''
            if args[1] == 'list-objects-v2':
                return json.dumps({'Contents': [{'Key': k, 'Size': len(v)} for k, v in remote.items() if k.startswith('lostopedia/database/')]})
            if args[1] == 'delete-object':
                del remote[args[args.index('--key') + 1]]
                return '{}'
            raise AssertionError(args)
        output = io.StringIO()
        with patch.object(self.backup, 's3', side_effect=s3), contextlib.redirect_stdout(output):
            self.backup.run()
        self.assertIn('Retained recovery points: 8', output.getvalue())
        self.assertEqual(remote['unrelated/keep'], b'untouched')
        self.assertEqual(len([k for k in remote if k.endswith('.complete.json')]), 8)
        self.assertFalse(any('/20260901' in k for k in remote))
        newest = max(k for k in remote if k.endswith('.tar.age'))
        ciphertext = self.root / 'download.age'
        ciphertext.write_bytes(remote[newest])
        archive = self.root / 'decrypted.tar.gz'
        subprocess.run(['age', '-d', '-i', str(identity), '-o', str(archive), str(ciphertext)], check=True, capture_output=True)
        extracted = self.root / 'extracted'
        with tarfile.open(archive) as tar:
            tar.extractall(extracted, filter='data')
        load('archive').verify(extracted)
        self.assertEqual(json.loads((extracted / 'organization.json').read_text()),
                         json.loads((Path(__file__).resolve().parents[3] / 'config/organization.json').read_text()))
        (extracted / 'data.sql').write_text('tampered')
        with self.assertRaises(ValueError):
            load('archive').verify(extracted)
        wrong = self.root / 'wrong-identity'
        subprocess.run(['age-keygen', '-o', str(wrong)], check=True, capture_output=True)
        failed = subprocess.run(['age', '-d', '-i', str(wrong), str(ciphertext)], capture_output=True)
        self.assertNotEqual(failed.returncode, 0)
        self.assertEqual(list(self.root.glob('lostopedia-backup-*')), [])


